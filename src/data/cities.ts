export function cityTotal(city: City): number {
  return STATS.reduce((sum, s) => sum + city.stats[s.key], 0);
}

export type Rarity = 'common' | 'rare' | 'epic' | 'legendary';

export const RARITY_INFO: Record<Rarity, { label: string; color: string; stars: number }> = {
  common: { label: 'Gewöhnlich', color: '#9CA3AF', stars: 1 },
  rare: { label: 'Selten', color: '#60A5FA', stars: 2 },
  epic: { label: 'Episch', color: '#C084FC', stars: 3 },
  legendary: { label: 'Legendär', color: '#FBBF24', stars: 4 },
};

export function cityRarity(city: City): Rarity {
  const avg = cityTotal(city) / STATS.length;
  if (avg >= 88) return 'legendary';
  if (avg >= 83) return 'epic';
  if (avg >= 76) return 'rare';
  return 'common';
}

/** Deterministische "Stadt des Tages" */
export function cityOfTheDay(date = new Date()): City {
  const day = Math.floor(Date.UTC(date.getFullYear(), date.getMonth(), date.getDate()) / 86400000);
  return CITIES[(day * 7) % CITIES.length];
}
